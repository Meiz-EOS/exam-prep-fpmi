/** Russian plural form of a counted noun: 1 билет, 2 билета, 5 билетов. */
function pluralWord(n: number, one: string, few: string, many: string): string {
  const [d, dd] = [Math.abs(n) % 10, Math.abs(n) % 100];
  return d === 1 && dd !== 11 ? one : d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? few : many;
}
const plural = (n: number, one: string, few: string, many: string): string => `${n} ${pluralWord(n, one, few, many)}`;

